enum {
  // The text both streams above hold: 20857 bytes whose CRC-32 is
  // 0x484d41d6.
  GZIP_TEST_TEXT_BYTES = 20857,
  GZIP_TEST_TEXT_CRC = 0x484d41d6,
  GZIP_TEST_FIXED_TEXT_BYTES = 500,
  GZIP_TEST_ROUND_TRIP_BYTES = 200000,
};

typedef struct GzipTestOutput {
  unsigned char *bytes;
  size_t length;
  size_t capacity;
  int calls;
} GzipTestOutput;

static bool gzip_test_sink(void *context, const unsigned char *bytes,
                           size_t length) {
  GzipTestOutput *output = (GzipTestOutput *)context;
  if (output->length + length > output->capacity) {
    output->capacity = (output->length + length) * 2;
    output->bytes = realloc_or_die(output->bytes, output->capacity);
  }
  memcpy(output->bytes + output->length, bytes, length);
  output->length += length;
  output->calls++;
  return true;
}

// Decompresses `length` bytes of gzip into `output` (which the caller frees).
static bool gzip_test_decompress(const unsigned char *gzip, size_t length,
                                 GzipTestOutput *output) {
  *output = (GzipTestOutput){0};
  FILE *stream = cmemfile_open(gzip, length);
  assert(stream);
  const bool decompressed =
      gzip_reader_decompress(stream, gzip_test_sink, output);
  fclose_or_die(stream);
  return decompressed;
}

void test_gzip_reader(void) {
  // Real gzip output, with dynamic and with fixed Huffman codes.
  GzipTestOutput output;
  bool decompressed = false;
  decompressed =
      gzip_test_decompress(dynamic_gzip, sizeof(dynamic_gzip), &output);
  assert(decompressed);
  assert(output.length == GZIP_TEST_TEXT_BYTES);
  assert(xs_crc32(output.bytes, output.length) == GZIP_TEST_TEXT_CRC);
  unsigned char *text = output.bytes;
  decompressed = gzip_test_decompress(fixed_gzip, sizeof(fixed_gzip), &output);
  assert(decompressed);
  assert(output.length == GZIP_TEST_FIXED_TEXT_BYTES);
  assert(memcmp(output.bytes, text, GZIP_TEST_FIXED_TEXT_BYTES) == 0);
  free(output.bytes);

  // Stored blocks (MAGPIE's own gzip writer), larger than the window, so the
  // output arrives in several pieces.
  unsigned char *random_bytes = malloc_or_die(GZIP_TEST_ROUND_TRIP_BYTES);
  uint32_t state = 12345;
  for (int byte_idx = 0; byte_idx < GZIP_TEST_ROUND_TRIP_BYTES; byte_idx++) {
    state = state * 1103515245U + 12345U;
    random_bytes[byte_idx] = (unsigned char)(state >> 16);
  }
  size_t compressed_length = 0;
  char *compressed =
      xs_gzip(random_bytes, GZIP_TEST_ROUND_TRIP_BYTES, &compressed_length);
  assert(compressed);
  decompressed = gzip_test_decompress((const unsigned char *)compressed,
                                      compressed_length, &output);
  assert(decompressed);
  assert(output.length == GZIP_TEST_ROUND_TRIP_BYTES);
  assert(output.calls > 1);
  assert(memcmp(output.bytes, random_bytes, GZIP_TEST_ROUND_TRIP_BYTES) == 0);
  free(output.bytes);

  // Two members back to back read as one stream, as gzip does.
  unsigned char *concatenated =
      malloc_or_die(compressed_length + sizeof(fixed_gzip));
  memcpy(concatenated, compressed, compressed_length);
  memcpy(concatenated + compressed_length, fixed_gzip, sizeof(fixed_gzip));
  decompressed = gzip_test_decompress(
      concatenated, compressed_length + sizeof(fixed_gzip), &output);
  assert(decompressed);
  assert(output.length ==
         GZIP_TEST_ROUND_TRIP_BYTES + GZIP_TEST_FIXED_TEXT_BYTES);
  free(output.bytes);
  free(concatenated);
  free(random_bytes);
  free(compressed);

  // A changed byte fails the CRC, a cut stream ends early, and something that
  // is not gzip is refused: never a silent success.
  unsigned char *corrupt = malloc_or_die(sizeof(dynamic_gzip));
  memcpy(corrupt, dynamic_gzip, sizeof(dynamic_gzip));
  corrupt[sizeof(dynamic_gzip) - 9] ^= 1;
  decompressed = gzip_test_decompress(corrupt, sizeof(dynamic_gzip), &output);
  assert(!decompressed);
  free(output.bytes);
  decompressed =
      gzip_test_decompress(dynamic_gzip, sizeof(dynamic_gzip) / 2, &output);
  assert(!decompressed);
  free(output.bytes);
  decompressed = gzip_test_decompress((const unsigned char *)"not gzip at all",
                                      15, &output);
  assert(!decompressed);
  free(output.bytes);
  free(corrupt);
  free(text);
}
