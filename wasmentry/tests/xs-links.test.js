test("@unit shared links reject ambiguous and malformed parameters", () => {
  const base = "https://magpie.birdtest.org/releases/wasm-preview-v0.1.3/wasmentry/?old=value#private";
  const token = "WFNQabcdefgh_-012345";
  expect(sharedLink(base, "xsp", token)).toBe(base.split("?")[0] + "?xsp=" + token);
  expect(readSharedLink(sharedLink(base, "xsg", token))).toEqual({kind: "xsg", token});
  expect(readSharedLink(base)).toBeNull();
  for (const query of ["xsp=", "xsp=a%00b", "xsg=abc+defghijk", `xsp=${token}&xsg=${token}`, `xsp=${token}&xsp=${token}`, `xsp=${"a".repeat(MAX_LINK_TOKEN + 1)}`]) {
    expect(() => readSharedLink("https://example.org/?" + query)).toThrow();
  }
});

async function clipboard(page, reject = false) {
  await page.addInitScript(reject => {
    window.copiedText = "";
    Object.defineProperty(navigator, "clipboard", {configurable: true, value: {
      writeText: async text => {
        if (reject) throw new Error("Clipboard unavailable");
        window.copiedText = text;
      },
    }});
  }, reject);
}

async function copied(page, button) {
  await openGameActions(page);
  await page.evaluate(() => { window.copiedText = ""; });
  await page.locator(button).click();
  await expect.poll(() => page.evaluate(() => window.copiedText || document.querySelector("#error").textContent), {timeout: 30000}).not.toBe("");
  await expect(page.locator("#error")).toBeEmpty();
  return page.evaluate(() => window.copiedText);
}

test("XSP copy/open preserves phonies, blanks, racks, lexicon and large scores", async ({page}) => {
  test.setTimeout(60000);
  await clipboard(page);
  await page.goto("/wasmentry/");
  await expect(page.locator("#status")).toHaveText("Engine ready");
  await openSample(page);
  await openGameActions(page);
  await page.locator("#import").click();
  const cgp = `7zQZX4/${Array(14).fill("15").join("/")} A?GINRS/AE 1200/-12 0 -lex NWL23`;
  await page.locator("#cgp").fill(cgp);
  await page.locator('#import-form button[type="submit"]').click();
  await expect(page.locator("#import-dialog")).toBeHidden();
  const expected = await copied(page, "#copy");
  const link = await copied(page, "#copy-position-link");
  expect(new URL(link).searchParams.has("xsp")).toBe(true);
  await page.goto(link);
  await expect(page.locator("#status")).toHaveText("Shared position loaded", {timeout: 30000});
  await expect(page.locator("#new-game-dialog")).toBeHidden();
  expect(await copied(page, "#copy")).toBe(expected);
  await page.locator('[data-mode="kibitz"]').click();
  await expect(page.locator("#status")).toHaveText("Complete", {timeout: 30000});
});

test("XSG game links preserve names and plays through the real engine", async ({page}) => {
  test.setTimeout(90000);
  await clipboard(page);
  await page.goto("/wasmentry/");
  await expect(page.locator("#status")).toHaveText("Engine ready");
  await openSample(page);
  await openGameActions(page);
  await page.locator("#load-gcg").click();
  await page.locator("#gcg-text").fill(await readFile("tests/fixtures/standard.gcg", "utf8"));
  await page.locator("#submit-gcg").click();
  await expect(page.locator("#gcg-dialog")).toBeHidden();
  const options = await page.locator("#history-position option").allTextContents();
  const link = await copied(page, "#copy-game-link");
  // Generated by native `conv gcg2xsg standard.gcg standard.xsg CSW24`.
  // This also checks that the frozen static ranks agree between native and WASM.
  expect(new URL(link).searchParams.get("xsg")).toBe((await readFile("tests/fixtures/standard.xsg", "utf8")).trim());
  await page.goto(link);
  await expect(page.locator("#status")).toHaveText("Shared game loaded", {timeout: 30000});
  await expect(page.locator("#error")).toBeEmpty();
  expect(await page.locator("#history-position option").allTextContents()).toEqual(options);
  const gcg = await copied(page, "#copy-gcg");
  expect(gcg).toContain("#player1 HastyBot HastyBot");
  expect(gcg).toContain("#player2 RightBehindYou RightBehindYou");
  expect(gcg).toContain("CRoWDIE");
});

test("damaged shared links leave startup usable and clipboard denial offers a selectable link", async ({page}) => {
  await page.setViewportSize({width: 390, height: 844});
  await clipboard(page, true);
  await page.goto("/wasmentry/?xsg=WFNHaaaaaaaaaaaaaaaa");
  await expect(page.locator("#error")).toContainText("Could not open shared link", {timeout: 30000});
  await expect(page.locator("#new-game-dialog")).toBeHidden();
  await page.locator("#new-game").click();
  await openSample(page);
  await openGameActions(page);
  await page.locator("#copy-position-link").click();
  await expect(page.locator("#share-link-dialog")).toBeVisible();
  await expect(page.locator("#share-link-text")).toBeInViewport();
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(390);
  expect(new URL(await page.locator("#share-link-text").inputValue()).searchParams.has("xsp")).toBe(true);
  await page.locator("#share-link-dialog button").click();
  await expect(page.locator("#copy-position-link")).toBeEnabled();
});

test("XSP corruption and ambiguous links fail gracefully", async ({page}) => {
  test.setTimeout(60000);
  for (const query of ["xsp=WFNQaaaaaaaaaaaaaaaa", "xsp=", "xsp=WFNQaaaaaaaaaaaaaaaa&xsg=WFNHaaaaaaaaaaaaaaaa"]) {
    await page.goto(`/wasmentry/?${query}`);
    await expect(page.locator("#error")).toContainText("Could not open shared link", {timeout: 30000});
    await expect(page.locator("#new-game")).toBeEnabled();
    await openGameActions(page);
    await expect(page.locator("#import")).toBeEnabled();
  }
});

test("failed codec downloads can be retried without losing the position", async ({page}) => {
  await clipboard(page);
  await page.route("**/CSW24.xsw.json.gz", route => route.fulfill({status: 503, body: "Unavailable"}), {times: 1});
  await page.goto("/wasmentry/");
  await expect(page.locator("#status")).toHaveText("Engine ready");
  await openSample(page);
  const cgp = await copied(page, "#copy");
  await openGameActions(page);
  await page.locator("#copy-position-link").click();
  await expect(page.locator("#error")).toContainText("HTTP 503");
  const link = await copied(page, "#copy-position-link");
  expect(new URL(link).searchParams.has("xsp")).toBe(true);
  expect(await copied(page, "#copy")).toBe(cgp);
});

test("game links refuse to drop a custom starting board", async ({page}) => {
  await clipboard(page);
  await page.goto("/wasmentry/");
  await expect(page.locator("#status")).toHaveText("Engine ready");
  await page.locator('[data-game-kind="record"]').click();
  await page.locator("#new-game-position > summary").click();
  const cgp = `15/15/15/15/15/15/15/7A7/${Array(7).fill("15").join("/")} AEINRST/BCDFGHJ 100/80 1 -lex NWL23`;
  await page.locator("#new-game-cgp").fill(cgp);
  await page.locator("#start-game").click();
  await expect(page.locator("#new-game-dialog")).toBeHidden();
  await openGameActions(page);
  await page.locator("#copy-game-link").click();
  await expect(page.locator("#error")).toContainText("Games started from a position cannot be shared");
  expect(await page.evaluate(() => window.copiedText)).toBe("");
  await expect(page.locator("#board .played")).toHaveCount(1);
  expect(new URL(await copied(page, "#copy-position-link")).searchParams.has("xsp")).toBe(true);
});

